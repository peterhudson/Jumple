"""Generate Jumple boards.

Each board is a 3x3 grid of nine different letters. A word is any dictionary
word of 4+ letters that uses each tile at most once; the tiles don't need to be
next to each other. Because the letters are all different, a word fits on a
board exactly when its letters are all different and all on the board, so the
generator looks up every subset of the board's letters instead of searching
paths.

Words are split into required words (common American English) and bonus words
(everything else in the dictionary). A board that spells a blocked word is
thrown away.

Usage: python3 tools/gen.py [count]
"""
import json, random, sys
from itertools import combinations
from pathlib import Path

HERE = Path(__file__).parent
SIZE = 9
MIN_LEN = 4
COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
SEED = 2026
# A comfortable number of required words: enough to dig for, not so many it drags.
REQUIRED = (25, 60)
TARGET = 40
ATTEMPTS = 150   # random boards tried for each board kept

def load(name):
    return [w.strip().upper() for w in open(HERE / 'data' / name)
            if w.strip() and not w.startswith('#')]

unblock = set(load('unblock.txt'))
blocked_roots = {w for w in load('blocklist.txt') if w.isalpha() and len(w) >= 3} - unblock
blocked = {root + suf for root in blocked_roots for suf in ('', 'S', 'ES', 'ED', 'ING', 'ER', 'ERS', 'Y')}
blocked = {w for w in blocked if MIN_LEN <= len(w) <= SIZE} - unblock

dictionary = {w for w in load('enable1.txt') if MIN_LEN <= len(w) <= SIZE and w.isalpha()} - blocked
# Required words are the ones most people know: SCOWL's American English list
# up to size 55, plus a few hand-picked extras, minus a few to avoid.
common = set(load('scowl-american-55.txt')) & dictionary
common |= set(load('promote.txt')) & dictionary
common -= set(load('avoid.txt'))

# Words keyed by their sorted letters. Only words with no repeated letter can be
# made from nine different tiles.
by_letters = {}
for w in dictionary | blocked:
    if len(set(w)) == len(w):
        by_letters.setdefault(''.join(sorted(w)), []).append(w)

def find_words(letters):
    found = []
    for n in range(MIN_LEN, SIZE + 1):
        for combo in combinations(sorted(letters), n):
            found += by_letters.get(''.join(combo), [])
    return found

# Rough English letter frequencies; a few rarer letters turn up now and then.
FILL = 'EEEEEEEEEEEAAAAAAAARRRRRRRIIIIIIIOOOOOOOTTTTTTTNNNNNNNSSSSSSLLLLLCCCCUUUUDDDPPPMMMHHHGGGBBFFYYWWKVXZJ'
VOWELS = set('AEIOU')
RARE = set('JXZVKW')

def random_letters(rng):
    letters = set()
    while len(letters) < SIZE:
        letters.add(rng.choice(FILL))
    return letters

def attempt(rng):
    letters = random_letters(rng)
    if not 2 <= len(letters & VOWELS) <= 4 or len(letters & RARE) > 1:
        return None
    found = find_words(letters)
    if any(w in blocked for w in found):
        return None
    required = sorted(w for w in found if w in common)
    if not REQUIRED[0] <= len(required) <= REQUIRED[1]:
        return None
    # Every tile must be part of some required word, like Squaredle.
    if set(''.join(required)) != letters:
        return None
    bonus = sorted(w for w in found if w not in common)
    longest = max(map(len, required))
    # Close to the target, with a long word to hunt for and not too many bonus words.
    # Rare letters thin out the word list, so without a nudge most boards would have one.
    score = -abs(len(required) - TARGET) + 3 * min(longest, 8) - 0.1 * len(bonus) - 6 * len(letters & RARE)
    return score, letters, required, bonus

def build(rng, seen):
    best = None
    tries = 0
    while best is None or tries < ATTEMPTS:
        tries += 1
        res = attempt(rng)
        if res and frozenset(res[1]) not in seen and (best is None or res[0] > best[0]):
            best = res
    _, letters, required, bonus = best
    seen.add(frozenset(letters))
    grid = list(letters)
    rng.shuffle(grid)
    return {'grid': ''.join(grid), 'words': required, 'bonus': bonus}

if __name__ == '__main__':
    rng = random.Random(SEED)
    seen, boards = set(), []
    for i in range(COUNT):
        b = build(rng, seen)
        boards.append(b)
        if i % 50 == 0:
            print(f"{i + 1:4} {b['grid']} required={len(b['words'])} bonus={len(b['bonus'])} "
                  f"longest={max(b['words'], key=len)}", file=sys.stderr, flush=True)
    out = HERE.parent / 'boards.js'
    out.write_text('// Generated by tools/gen.py. Do not edit by hand.\n'
                   '// Board n is the daily Jumple n days after the first one.\nconst BOARDS = [\n'
                   + ',\n'.join(json.dumps(b, separators=(',', ':')) for b in boards) + '\n];\n')
